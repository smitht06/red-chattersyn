"""Highlight/mention matching at message ingress (Chatterino parity).

HighlightController subscribes bridge.message ahead of the UI router, so the
HIGHLIGHTED flag is set before a row is first painted. Match sources, in
precedence order:

1. **mention** — the message text contains my login or display name (Twitch
   identity; YouTube messages are checked against the same names), only when
   `notifications.mentions` is on. Own messages and system rows are excluded;
   a mention uses the global `highlight_color` and `notifications.sound`.
2. **highlight entries** from settings `highlights` —
   {text, regex, case_sensitive, color, alert, sound}; the first matching
   entry wins. Entries also match system rows (Chatterino does).

A hit sets MessageFlags.HIGHLIGHTED, records the colour in
msg.extra["highlight_color"] (the delegate prefers it over the global
`highlight_color`), appends the message to the bounded mention store behind
the /mentions popup, and emits `highlighted`. Sound plays through one shared
QSoundEffect with a cooldown so a burst doesn't stack pings; `alert` flashes
the dock/taskbar icon via QApplication.alert (only when the window is not
active).

The matcher itself is UI-agnostic and pure — tests cover it directly.
"""

from __future__ import annotations

import logging
import re
import time
from collections import deque
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from PySide6.QtCore import QObject, QUrl, Signal
from PySide6.QtWidgets import QApplication

from ..config.settings import Settings
from ..core.bus import bridge
from ..models.message import Author, Message, MessageFlags

log = logging.getLogger(__name__)

_SOUND_COOLDOWN = 0.4  # seconds between pings — a 50 msg/s burst pings once

# Bundled chime (generated by scripts/../assets — two decaying sines).
PING_PATH = Path(__file__).resolve().parent.parent / "assets" / "ping.wav"


@dataclass
class HighlightHit:
    kind: str            # "mention" | "highlight"
    color: str           # hex colour for the row tint ("" -> delegate default)
    sound: bool          # play the ping
    alert: bool          # flash the taskbar/dock icon


@dataclass
class _Entry:
    text: str
    case_sensitive: bool
    color: str
    alert: bool
    sound: bool
    compiled: re.Pattern[str] | None = None  # None -> plain substring

    def matches(self, plain: str) -> bool:
        if self.compiled is not None:
            return self.compiled.search(plain) is not None
        if self.case_sensitive:
            return self.text in plain
        return self.text.lower() in plain.lower()


class HighlightMatcher:
    """Compiles settings highlights; `match` returns the winning hit or None."""

    def __init__(self, settings: Settings):
        self._settings = settings
        self._entries: list[_Entry] = []
        self.refresh()
        settings.changed.connect(self.refresh)

    def refresh(self) -> None:
        entries: list[_Entry] = []
        raw = self._settings.get("highlights", [])
        if isinstance(raw, list):
            for item in raw:
                if not isinstance(item, dict):
                    continue
                text = str(item.get("text") or "")
                if not text:
                    continue
                case_sensitive = bool(item.get("case_sensitive"))
                compiled = None
                if item.get("regex"):
                    try:
                        compiled = re.compile(
                            text, 0 if case_sensitive else re.IGNORECASE)
                    except re.error as exc:
                        log.warning("Ignoring invalid highlight regex %r: %s", text, exc)
                        continue
                entries.append(_Entry(
                    text=text,
                    case_sensitive=case_sensitive,
                    color=str(item.get("color") or "") or self._settings.get("highlight_color", "#7a5cff"),
                    alert=bool(item.get("alert")),
                    sound=bool(item.get("sound")),
                    compiled=compiled,
                ))
        self._entries = entries

    def match(self, msg: Message, self_login: str = "", self_name: str = "") -> HighlightHit | None:
        if (bool(self._settings.get("notifications.mentions", True))
                and self._is_mention(msg, self_login, self_name)):
            return HighlightHit(
                kind="mention",
                color=self._settings.get("highlight_color", "#7a5cff"),
                sound=bool(self._settings.get("notifications.sound", False)),
                alert=False,
            )
        for entry in self._entries:
            if entry.matches(msg.plain):
                return HighlightHit(
                    kind="highlight",
                    color=entry.color,
                    sound=entry.sound,
                    alert=entry.alert,
                )
        return None

    @staticmethod
    def _is_mention(msg: Message, self_login: str, self_name: str) -> bool:
        if not self_login or msg.author is None or msg.is_system:
            return False  # no identity, system rows and own messages never ping
        if (msg.author.login or "").lower() == self_login.lower():
            return False
        plain = msg.plain.lower()
        return (self_login.lower() in plain
                or (bool(self_name) and self_name.lower() in plain))


class HighlightController(QObject):
    """Ingress subscriber: flags matches, stores them, pings, flashes."""

    highlighted = Signal(object)  # Message — live feed for the /mentions popup

    def __init__(self, settings: Settings):
        super().__init__()
        self._settings = settings
        self._matcher = HighlightMatcher(settings)
        self._identity: Callable[[], Author | None] | None = None
        cap = max(1, int(settings.get("scrollback", 1000) or 1000))
        self._store: deque[Message] = deque(maxlen=cap)
        self._conn = None
        self._window = None
        self._ping = None
        self._last_sound = 0.0

    def set_identity_provider(self, provider: Callable[[], Author | None]) -> None:
        """Identity for mention detection (TwitchService.self_author)."""
        self._identity = provider

    def start(self, window=None) -> None:
        self._window = window
        self._conn = bridge.message.connect(self._on_message)
        self._ping = self._make_ping()

    def stop(self) -> None:
        if self._conn is not None:
            bridge.message.disconnect(self._conn)
            self._conn = None

    # -- store ----------------------------------------------------------------------

    def messages(self) -> list[Message]:
        """Highlighted messages, newest first (the /mentions view)."""
        return list(reversed(self._store))

    def clear(self) -> None:
        self._store.clear()

    # -- ingress --------------------------------------------------------------------

    def _on_message(self, msg: Message) -> None:
        login, name = "", ""
        if self._identity is not None:
            author = self._identity()
            if author is not None:
                login, name = author.login or "", author.name or ""
        hit = self._matcher.match(msg, login, name)
        if hit is None:
            return
        msg.flags |= MessageFlags.HIGHLIGHTED
        if hit.color:
            msg.extra["highlight_color"] = hit.color
        self._store.append(msg)
        self.highlighted.emit(msg)
        if hit.sound:
            self._play_sound()
        if hit.alert and self._window is not None:
            QApplication.alert(self._window, 0)

    # -- sound -----------------------------------------------------------------------

    @staticmethod
    def _make_ping():
        if not PING_PATH.exists():
            return None
        try:
            from PySide6.QtMultimedia import QSoundEffect
        except ImportError:  # pragma: no cover
            return None
        try:
            effect = QSoundEffect()
            effect.setSource(QUrl.fromLocalFile(str(PING_PATH)))
            effect.setVolume(0.9)
            return effect
        except RuntimeError as exc:  # no audio backend
            log.warning("QSoundEffect unavailable: %s", exc)
            return None

    def _play_sound(self) -> None:
        if self._ping is None:
            return
        now = time.monotonic()
        if now - self._last_sound < _SOUND_COOLDOWN:
            return
        self._last_sound = now
        self._ping.play()
